// Helper to generate full triage report
function createSampleReport(
  id: string,
  animal: Animal,
  transcript: string,
  symptoms: ('fever' | 'reduced_feed' | 'reduced_milk' | 'lameness' | 'mouth_lesions' | 'drooling' | 'swelling' | 'mastitis_signs')[],
  daysAgo: number,
  assignedVetId?: string,
  assignedVetName?: string
): { report: SymptomReport; caseTracking?: CaseTracking } {
  const createdDate = new Date(Date.now() - daysAgo * 24 * 60 * 60 * 1000).toISOString();
  const triage = evaluateTriageRules(symptoms);
  const triageResult = {
    id: `tr-${id}`,
    urgency: triage.urgency,
    headline: triage.headline,
    headlineKn: triage.headlineKn,
    calmMessage: triage.calmMessage,
    calmMessageKn: triage.calmMessageKn,
    gentleConcerns: triage.gentleConcerns,
    gentleConcernsKn: triage.gentleConcernsKn,
    nextActions: triage.nextActions,
    nextActionsKn: triage.nextActionsKn,
    detectedSymptoms: symptoms,
    isLowConfidence: triage.isLowConfidence,
    clusterFlag: false,
    disclaimers: MANDATORY_DISCLAIMERS,
  };

  const report: SymptomReport = {
    id,
    animalId: animal.id,
    animalName: animal.name,
    ownerId: animal.ownerId,
    ownerName: animal.ownerName,
    village: animal.village,
    transcript,
    symptoms,
    triageResult,
    createdAt: createdDate,
    synced: true,
    assignedCaseId: `case-${id}`,
  };

  const caseTracking: CaseTracking = {
    id: `case-${id}`,
    reportId: id,
    animalId: animal.id,
    animalName: animal.name,
    ownerName: animal.ownerName,
    ownerPhone: '9845012345',
    village: animal.village,
    status: triage.urgency === 'RED' ? 'Under Review' : triage.urgency === 'ORANGE' ? 'Visit Scheduled' : 'Pending',
    urgency: triage.urgency,
    symptoms,
    assignedVetId: assignedVetId || 'vet-anil',
    assignedVetName: assignedVetName || 'Dr. Anil Kumar',
    reportedAt: createdDate,
    updatedAt: createdDate,
    visitScheduledDate: triage.urgency === 'ORANGE' ? new Date(Date.now() + 4 * 3600 * 1000).toISOString() : undefined,
    vetNotes: triage.urgency === 'RED' ? 'Priority veterinary review initiated.' : undefined,
    timeline: [
      { stage: 'Pending', timestamp: createdDate, note: 'Triage reported by dairy farmer' },
      ...(triage.urgency === 'RED'
        ? [{ stage: 'Under Review' as const, timestamp: createdDate, note: 'Reviewed by Dr. Anil Kumar' }]
        : triage.urgency === 'ORANGE'
        ? [
            { stage: 'Under Review' as const, timestamp: createdDate, note: 'Reviewed by Dr. Anil Kumar' },
            { stage: 'Visit Scheduled' as const, timestamp: createdDate, note: 'Field visit scheduled for afternoon' },
          ]
        : []),
    ],
  };

  return { report, caseTracking };
}

